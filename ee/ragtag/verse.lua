VERSE.transports = {}
VERSE.wrecks = {}
VERSE.places = {}       -- name -> {x, y} in world units, for scenarios
VERSE.discovered_this_session = {}
VERSE.region = nil
VERSE.last_region_check = -10
VERSE.respawn_queue = {}
VERSE.session = 1

local function buildStars()
    for _, s in ipairs(VERSE.STARS) do
        local p = Planet():setPosition(s.x * U, s.y * U):setPlanetRadius(s.r * U)
        p:setDistanceFromMovementPlane(-s.r * U * 0.6)
        p:setPlanetAtmosphereTexture("planets/star-1.png")
        p:setPlanetAtmosphereColor(s.color[1], s.color[2], s.color[3])
        p:setCallSign(s.name)
        VERSE.places[s.name] = {x = s.x * U, y = s.y * U}
    end
end

local function buildPlanets()
    for _, d in ipairs(VERSE.PLANETS) do
        local p = Planet():setPosition(d.x * U, d.y * U):setPlanetRadius(d.r * U)
        p:setDistanceFromMovementPlane(-d.r * U * 0.4)
        p:setPlanetSurfaceTexture(d.tex)
        if d.clouds then p:setPlanetCloudTexture(d.clouds):setPlanetCloudRadius(d.r * U * 1.05) end
        if d.atmo then
            p:setPlanetAtmosphereTexture("planets/atmosphere.png")
            p:setPlanetAtmosphereColor(d.atmo[1], d.atmo[2], d.atmo[3])
        end
        p:setAxialRotationTime(400)
        p:setCallSign(d.name)
        p:setDescription(d.desc)
        VERSE.places[d.name] = {x = d.x * U, y = d.y * U}
    end
end

local function buildStations()
    for _, d in ipairs(VERSE.STATIONS) do
        local s
        if d.fac == "Corsairs" or d.fac == "Hollow" then
            s = SpaceStation():setTemplate(d.tmpl):setFaction(d.fac):setPosition(d.x * U, d.y * U):setCallSign(d.cs)
            s:setDescription(d.desc)
            s:setCommsFunction(function(source, target)
                setCommsMessage(target:getFaction() == "Hollow" and "Something answers. It is not language." or
                    "\"Wrong neighbourhood, freighter. Turn around or we'll take your hull for scrap.\"")
            end)
            RT.register(s)
        else
            s = RT.station({template = d.tmpl, faction = d.fac, callsign = d.cs, x = d.x * U, y = d.y * U,
                shop = d.shop or false, flavor = d.flavor, description = d.desc})
            RT.stations[d.cs].concord = d.concord or false
        end
        VERSE.places[d.cs] = {x = d.x * U, y = d.y * U}
    end
end

local function buildNebulae(rng)
    for _, f in ipairs(VERSE.NEBULA_FIELDS) do
        for i = 1, f.count do
            local a = rng.float(0, 360)
            local d = math.sqrt(rng.float(0, 1)) * f.r
            local dx, dy = vectorFromAngle(a, d * U, true)
            Nebula():setPosition(f.x * U + dx, f.y * U + dy)
        end
    end
end

-- Points asteroids must keep clear of (stations, planets, suns), in units.
local function keepOutZones()
    local z = {}
    for _, d in ipairs(VERSE.STATIONS) do table.insert(z, {x = d.x, y = d.y, r = 4}) end
    for _, d in ipairs(VERSE.PLANETS) do table.insert(z, {x = d.x, y = d.y, r = d.r + 2}) end
    for _, d in ipairs(VERSE.STARS) do table.insert(z, {x = d.x, y = d.y, r = d.r + 2}) end
    return z
end

local function blocked(zones, x, y)
    for _, z in ipairs(zones) do
        local dx, dy = x - z.x, y - z.y
        if dx * dx + dy * dy < z.r * z.r then return true end
    end
    return false
end

local function buildAsteroids(rng)
    local zones = keepOutZones()
    for _, f in ipairs(VERSE.ASTEROID_FIELDS) do
        local function place(ctor, n)
            for i = 1, n do
              for attempt = 1, 6 do
                local x, y
                if f.kind == "belt" then
                    local t = rng.float(0, 1)
                    local off = rng.float(-f.width / 2, f.width / 2)
                    local lx, ly = f.x2 - f.x1, f.y2 - f.y1
                    local len = math.sqrt(lx * lx + ly * ly)
                    x = f.x1 + lx * t + (-ly / len) * off
                    y = f.y1 + ly * t + (lx / len) * off
                else
                    local a = rng.float(0, 360)
                    local d = math.sqrt(rng.float(0, 1)) * f.r
                    local dx, dy = vectorFromAngle(a, d, true)
                    x, y = f.x + dx, f.y + dy
                end
                if not blocked(zones, x, y) or attempt == 6 then
                    if not blocked(zones, x, y) then
                        local o = ctor():setPosition(x * U, y * U)
                        if ctor == Asteroid then o:setSize(rng.float(80, 260)) end
                    end
                    break
                end
              end
            end
        end
        place(Asteroid, f.count)
        place(VisualAsteroid, f.visual or 0)
    end
end

local function buildMines()
    for _, m in ipairs(VERSE.MINEFIELDS) do
        for i = 0, m.count - 1 do
            local a = (360 / m.count) * i
            local diff = math.abs(((a - m.gap_angle) + 180) % 360 - 180)
            if diff > m.gap_width / 2 then
                local dx, dy = vectorFromAngle(a, m.r * U, true)
                Mine():setPosition(m.x * U + dx, m.y * U + dy)
            end
        end
    end
end

local function buildHazards()
    for _, h in ipairs(VERSE.HAZARDS) do
        if h.kind == "blackhole" then
            BlackHole():setPosition(h.x * U, h.y * U)
        elseif h.kind == "wormhole" then
            local w = WormHole():setPosition(h.x * U, h.y * U):setTargetPosition(h.tx * U, h.ty * U)
            if h.desc then w:setDescription(h.desc) end
        end
    end
end

local function buildGarrisons()
    local n = 0
    for _, g in ipairs(VERSE.GARRISONS) do
        for i, tmpl in ipairs(g.ships) do
            local dx, dy = vectorFromAngle((360 / #g.ships) * i, (#g.ships > 1) and 700 or 0, true)
            local s = CpuShip():setTemplate(tmpl):setFaction(g.fac):setPosition(g.x * U + dx, g.y * U + dy)
            if g.callsign and i == 1 then s:setCallSign(g.callsign) end
            if g.idle then
                s:orderIdle()
            else
                s:orderDefendLocation(g.x * U, g.y * U)
            end
            if g.fac == "Unknown" then
                s:setCommsFunction(function() setCommsMessage("A burst of compressed tone. Then nothing.") end)
                s:setDescriptions("No transponder.", "Hull configuration matches no registry. Emissions are... rhythmic.")
            elseif g.fac == "Concord" then
                s:setCommsFunction(concordPatrolComms)
                s:setDescriptions("CWS-registered warship.", "Concord Navy. Base defense posting.")
                s:setDescriptionForScanState("fullscan", "Permanent sector assignment. Authorized to enforce Concord law and customs within this region. Not actively targeting independent traffic — unless you give them a reason.")
                s:setScanningParameters(1, 2)
            elseif g.fac == "Corsairs" then
                s:setCommsFunction(function(source, target)
                    setCommsMessage("\"Corsair space, little freighter. Your cargo or your hull - we're easy either way.\"")
                end)
                if g.role == "port" then
                    s:setDescriptions("Unknown vessel.", "Corsair port defender. Territorial patrol.")
                    s:setDescriptionForScanState("fullscan", "Blackwater defense patrol. These ships aren't hunting — they're guarding. Walk in shooting and you'll meet everything they have.")
                    s:setScanningParameters(1, 2)
                end
            elseif g.fac == "Independent" and g.role == "port" then
                s:setDescriptions("Defense platform.", "Port defense platform. Perimeter emplacement.")
                s:setDescriptionForScanState("fullscan", "Automated defense grid maintained by Lastchance Outpost. Old Concord hardware, still functional. These don't follow you — they hold the line against whatever comes out of the Maw.")
                s:setScanningParameters(1, 2)
            end
            RT.register(s)
            if DIR then DIR.registerKill(s) end
            n = n + 1
        end
    end
    return n
end

local function concordPatrolComms(source, target)
    if RT.flag("wanted") then
        setCommsMessage("\"" .. source:getCallSign() .. ", your transponder is flagged. Keep your distance and keep moving.\"")
    else
        setCommsMessage("\"Concord patrol " .. target:getCallSign() .. ". Lanes are clear. Keep it that way.\"")
    end
end

local function stripWeapons(s)
    for i = 0, 15 do
        local r = s:getBeamWeaponRange(i)
        if r ~= nil and r > 0 then s:setBeamWeapon(i, 0, 0, 0, 0, 0) end
    end
    s:setWeaponTubeCount(0)
end

local function buildWrecks(rng)
    local zones = keepOutZones()
    for _, f in ipairs(VERSE.WRECK_FIELDS) do
        for i = 1, f.count do
            local dx, dy
            for attempt = 1, 8 do
                local a = rng.float(0, 360)
                local d = math.sqrt(rng.float(0, 1)) * f.r
                dx, dy = vectorFromAngle(a, d, true)
                if not blocked(zones, f.x + dx, f.y + dy) then break end
            end
            local tmpl = rng.pick(f.templates)
            local name = f.names[i] or ("Wreck " .. i)
            local s = CpuShip():setTemplate(tmpl):setFaction("Derelict"):setPosition((f.x + dx) * U, (f.y + dy) * U)
            s:setCallSign(name):orderIdle():setImpulseMaxSpeed(0):setRotationMaxSpeed(0)
            s:setHeading(rng.float(0, 360))
            stripWeapons(s)
            s:setShieldsMax(0)
            s:setHull(math.max(1, s:getHullMax() * 0.15))
            s:setCanBeDestroyed(false)
            s:setDescriptions("Unpowered hull.", (f.desc:gsub("{name}", name)) .. " Science: salvageable compartments detected.")
            s:setScanningParameters(1, 2)
            s:setCommsFunction(function() setCommsMessage("Dead air.") end)
            RT.register(s)
            table.insert(VERSE.wrecks, {ship = s, tier = f.tier, looted = false})
        end
    end
end



