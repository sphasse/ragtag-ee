-- opts.session: session number
function VERSE.build(opts)
    opts = opts or {}
    VERSE.session = opts.session or 1
    if not VERSE.factions_ready then VERSE.setupFactions() end
    local map_rng = VERSE.rng(VERSE.SEED)
    VERSE.rng_live = VERSE.rng(VERSE.SEED + 7919 * VERSE.session + math.floor(random(0, 100000)))

    buildStars()
    buildPlanets()
    buildStations()
    buildNebulae(map_rng)
    buildAsteroids(map_rng)
    buildMines()
    buildHazards()
    VERSE.garrison_count = buildGarrisons()
    buildWrecks(map_rng)
    -- Salvage clusters and wreck scanning are handled by the WORLD "salvage" plugin.
    -- Freighter traffic and ambient crates are handled by the WORLD "traffic" plugin.

    if DIR then
        DIR.addStateProvider(function()
            return {region = VERSE.region and VERSE.region.name or "open space",
                    region_danger = VERSE.region and VERSE.region.danger or 0,
                    transports_active = #VERSE.transports}
        end)
    end
end

function VERSE.update(delta)
    local now = getScenarioTime()
    if now - VERSE.last_region_check >= 2 then
        VERSE.last_region_check = now
        VERSE.updateRegion()
    end
    -- Traffic, ambient crates, and wreck scanning are driven by WORLD plugins.
end

-- Scenarios declare the places they depend on. Missing ones are reported to
-- the GM and the log (tools/check.py catches this before it reaches a game).
function VERSE.requirePlaces(names)
    local missing = {}
    for _, n in ipairs(names) do
        if VERSE.places[n] == nil then table.insert(missing, n) end
    end
    if #missing > 0 then
        local msg = "This scenario needs places the universe doesn't have: " .. table.concat(missing, ", ")
        print("[VERSE] " .. msg)
        addGMMessage(msg)
    end
    return missing
end

-- Position helper for scenarios: VERSE.at("Port Vesper", dx_u, dy_u) -> x, y world units
function VERSE.at(name, dx, dy)
    local p = VERSE.places[name]
    if p == nil then return 0, 0 end
    return p.x + (dx or 0) * U, p.y + (dy or 0) * U
end
