VERSE.OPEN_SPACE = {name = "open space", danger = 0, desc = "Open space between the charted regions."}

function VERSE.regionAt(x, y)
    local best, best_r = VERSE.OPEN_SPACE, math.huge
    for _, r in ipairs(VERSE.REGIONS) do
        local dx, dy = x / U - r.x, y / U - r.y
        if dx * dx + dy * dy <= r.r * r.r and r.r < best_r then
            best, best_r = r, r.r
        end
    end
    return best
end

local DANGER_LABEL = {[0] = "safe", [1] = "risky", [2] = "dangerous", [3] = "DEADLY"}

local function isDiscovered(name)
    for _, n in ipairs(RT.campaign.discovered or {}) do
        if n == name then return true end
    end
    return false
end

function VERSE.updateRegion()
    local p = RT.player
    if not RT.valid(p) then return end
    local x, y = p:getPosition()
    local r = VERSE.regionAt(x, y)
    if r == VERSE.region then return end
    VERSE.region = r
    local label = "Location: " .. r.name .. " (" .. DANGER_LABEL[r.danger] .. ")"
    p:addCustomInfo("helms", "rt_region", label, 1)
    p:addCustomInfo("relay", "rt_region_r", label, 1)
    p:addCustomInfo("operations", "rt_region_o", label, 1)
    if r == VERSE.OPEN_SPACE then return end

    local first_ever = not isDiscovered(r.name)
    local first_session = not VERSE.discovered_this_session[r.name]
    VERSE.discovered_this_session[r.name] = true
    if first_ever then
        if type(RT.campaign.discovered) ~= "table" then RT.campaign.discovered = {} end
        table.insert(RT.campaign.discovered, r.name)
        p:addToShipLog("Charted: " .. r.desc, "#A0E0FF")
        RT.addCredits(10 + 15 * r.danger, "survey data for " .. r.name, p)
    elseif first_session then
        p:addToShipLog("Entering " .. r.name .. ".", "#A0E0FF")
    end
    if r.danger >= 2 and first_session then
        p:addToShipLog("WARNING: " .. r.name .. " is " .. DANGER_LABEL[r.danger] .. " for a ship like this.", "#FF6060")
        if r.danger >= 3 then globalMessage("NAV WARNING: Entering " .. r.name .. ". Turn back.", 8) end
    end
    if DIR then
        DIR.emit("region_entered", {region = r.name, danger = r.danger, first_visit = first_ever, desc = r.desc},
            r.danger >= 2 and "high" or (first_ever and "normal" or "low"))
    end
end

