function VERSE.setupFactions()
    local ind = getFactionInfo("Independent")
    local function make(name, r, g, b, desc)
        local f = getFactionInfo(name)
        if f == nil then
            f = FactionInfo():setName(name):setLocaleName(name)
        end
        f:setGMColor(r, g, b)
        f:setDescription(desc)
        return f
    end
    local concord = make("Concord", 110, 170, 255,
        "The Concord governs the Core worlds and claims the rest. Customs patrols, permits and inspections. Most of its officers are decent people inside a system that is not.")
    local corsairs = make("Corsairs", 255, 140, 60,
        "Pirate crews who prey on the freight lanes. They hold Blackwater Reach and work the Gauntlet. Greedy, theatrical, and dangerous in numbers.")
    local hollow = make("Hollow", 220, 0, 0,
        "Nobody agrees on what the Hollow are. Their ships come from beyond the Pale Sun and they do not negotiate. Spacers who see Hollow running lights turn around.")
    local relic = make("Relic", 210, 200, 90,
        "Automated war drones left over from the Settlement War, still guarding the battlefield around Ashgrave. They attack anything that moves.")
    local unknown = make("Unknown", 180, 140, 255,
        "No transponder. No registry. No voice. Seen only deep in the Shroud.")
    local derelict = make("Derelict", 120, 120, 120,
        "Dead hulls. Nobody aboard, nothing powered.")

    corsairs:setEnemy(ind)
    corsairs:setEnemy(concord)
    hollow:setEnemy(ind)
    hollow:setEnemy(concord)
    hollow:setEnemy(corsairs)
    hollow:setEnemy(unknown)
    relic:setEnemy(ind)
    relic:setEnemy(concord)
    relic:setEnemy(corsairs)
    relic:setEnemy(hollow)
    VERSE.factions_ready = true
end

