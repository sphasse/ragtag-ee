-- ee/ragtag/verse.lua
-- The universe engine: builds whatever universe data has been loaded through
-- VERSE.extend() (the base map in verse/drift.lua plus any files in
-- verse/extensions/). This file holds no map data of its own.
--
-- Inspired by the structure of the Firefly 'Verse: a rich Core around a white
-- sun, Border worlds, a lawless Rim, a dead world left over from an old war,
-- and at the far edge, under a blue sun, the raiders everyone is afraid of.
-- All names here are our own.
--
-- The layout is generated from a fixed seed so the map is identical every
-- session. Salvage clusters are spawned by the WORLD "salvage" plugin.
--
-- Usage (in init(), before creating anything else):
--   VERSE.setupFactions()
--   VERSE.build({session = 1})
--   VERSE.requirePlaces({"Port Vesper", ...})   -- declare what the scenario depends on
-- and in update(delta):
--   VERSE.update(delta)
--
-- Coordinates in the data tables are in units (u); 1u = 1000 world units.

VERSE = VERSE or {}
require("ragtag/verse/schema.lua")
require("ragtag/verse/drift.lua")
do
    -- Community extensions. index.lua is generated by tools/install.py and
    -- tools/check.py --fix; a missing index just means no extensions.
    local ok, err = pcall(require, "ragtag/verse/extensions/index.lua")
    if not ok and not tostring(err):find("not found") and not tostring(err):find("cannot open") then
        print("[VERSE] extension load failed: " .. tostring(err))
    end
end
VERSE.SEED = 20261022
VERSE.U = 1000

--------------------------------------------------------------------------------
-- Deterministic random numbers (xorshift32), independent of the engine's RNG
--------------------------------------------------------------------------------

function VERSE.rng(seed)
    local s = seed & 0xffffffff
    if s == 0 then s = 0x9e3779b9 end
    local r = {}
    function r.next()
        s = s ~ ((s << 13) & 0xffffffff)
        s = s ~ (s >> 17)
        s = s ~ ((s << 5) & 0xffffffff)
        return s
    end
    function r.float(a, b) return a + (b - a) * (r.next() / 4294967296) end
    function r.int(a, b) return a + (r.next() % (b - a + 1)) end
    function r.pick(t) return t[r.int(1, #t)] end
    function r.chance(p) return r.float(0, 1) < p end
    return r
end

