-- ee/ragtag/arena.lua
-- ARENA: the Combat Arena (scenarios/arena/scenario_65_arena.lua), for balancing encounters. The GM
-- builds a roster of enemy ships from the ship types the Drift uses, spawns it frozen at a chosen
-- distance in front of the crews, starts the fight, and reads a report: the two sides' strength
-- (RT.shipStrength), the time taken and what was left of each ship. "Restore" puts every player
-- ship back to a healthy start (hull, shields, energy, systems, missiles, probes).
-- The GM screen is here too (ARENA.showGM, at the end), with the campaign's Ship Upgrades... menu.
-- Loaded by the arena scenario, not by core. Testable without the scenario: tests/core/arena.lua.

ARENA = ARENA or {}

local U = 1000

ARENA.DIST_MIN, ARENA.DIST_MAX = 2, 10   -- spawn distance, U from the centre of the player ships
ARENA.DIST_DEFAULT = 6
ARENA.MAX_PER_TYPE = 20
ARENA.ROW = 8              -- enemies per row; further rows stand behind the first
ARENA.SPACING_U = 0.8      -- between neighbours in a row, and between rows
-- Every faction an enemy can fly for: all hostile to the crews (Independent). One faction a fight.
ARENA.FACTIONS = {"Corsairs", "Shroud Raiders", "Concord Hostile", "Relic", "Hollow"}
ARENA.SYSTEMS = {"reactor", "beamweapons", "missilesystem", "maneuver", "impulse", "warp", "jumpdrive",
                 "frontshield", "rearshield"}
ARENA.MISSILES = {"Homing", "Nuke", "Mine", "EMP", "HVLI"}

-- phase: "empty" (no enemies) -> "frozen" (spawned, idle) -> "fighting" -> "over" (one side gone).
function ARENA.reset()
    ARENA.state = {roster = {}, dist_u = ARENA.DIST_DEFAULT, faction = ARENA.FACTIONS[1], enemies = {},
                   phase = "empty", fights = 0}
end
if not ARENA.state then ARENA.reset() end

local function _now() return getScenarioTime() end

local function _players()
    local out = {}
    for _, p in ipairs(RT.players) do if RT.valid(p) then out[#out + 1] = p end end
    return out
end

-- ── The ship types ───────────────────────────────────────────────────────────
-- The AI ship types the Drift's Lua names (SCIDB.SHIPS_USED, generated by check.py --fix), armed
-- ones only: no player ships, stations, freighters or tugs. Sorted by name.
function ARENA.templates()
    local out = {}
    for name in pairs(SCIDB and SCIDB.SHIPS_USED or {}) do
        local t = __ship_templates and __ship_templates[name]
        if t and (t.__type == nil or t.__type == "ship") then
            local armed = (t.beam_weapons and #t.beam_weapons > 0) or (t.missile_tubes and #t.missile_tubes > 0)
            if armed then out[#out + 1] = name end
        end
    end
    table.sort(out)
    return out
end

-- ── The roster ───────────────────────────────────────────────────────────────
function ARENA.count(name) return ARENA.state.roster[name] or 0 end

-- Add n of a type (negative takes some away); 0 to ARENA.MAX_PER_TYPE. Returns the new count.
function ARENA.add(name, n)
    local c = math.max(0, math.min(ARENA.MAX_PER_TYPE, ARENA.count(name) + (n or 1)))
    ARENA.state.roster[name] = (c > 0) and c or nil
    return c
end

function ARENA.clearRoster() ARENA.state.roster = {} end

function ARENA.rosterSize()
    local n = 0
    for _, c in pairs(ARENA.state.roster) do n = n + c end
    return n
end

-- The roster's types in name order, each repeated by its count.
function ARENA.rosterList()
    local names = {}
    for name in pairs(ARENA.state.roster) do names[#names + 1] = name end
    table.sort(names)
    local out = {}
    for _, name in ipairs(names) do
        for _ = 1, ARENA.state.roster[name] do out[#out + 1] = name end
    end
    return out
end

-- "2 x Adder MK5, 1 x Phobos T3", or "(empty)".
function ARENA.rosterText()
    local names = {}
    for name in pairs(ARENA.state.roster) do names[#names + 1] = name end
    table.sort(names)
    local parts = {}
    for _, name in ipairs(names) do parts[#parts + 1] = ARENA.state.roster[name] .. " x " .. name end
    return #parts > 0 and table.concat(parts, ", ") or "(empty)"
end

function ARENA.setDistance(u)
    ARENA.state.dist_u = math.max(ARENA.DIST_MIN, math.min(ARENA.DIST_MAX, math.floor((tonumber(u) or ARENA.DIST_DEFAULT) + 0.5)))
    return ARENA.state.dist_u
end
function ARENA.nudgeDistance(d) return ARENA.setDistance(ARENA.state.dist_u + d) end

function ARENA.cycleFaction()
    local i = 1
    for k, f in ipairs(ARENA.FACTIONS) do if f == ARENA.state.faction then i = k end end
    ARENA.state.faction = ARENA.FACTIONS[i % #ARENA.FACTIONS + 1]
    return ARENA.state.faction
end

-- ── Spawning and the fight ───────────────────────────────────────────────────
-- Where the enemies line up: `dist_u` from the centre of the live player ships, ahead of the primary
-- ship's heading (north without one), in rows of ARENA.ROW across that line, facing the crews.
function ARENA.centre()
    local ps = _players()
    if #ps == 0 then return nil end
    local x, y = 0, 0
    for _, p in ipairs(ps) do
        local px, py = p:getPosition()
        x, y = x + px, y + py
    end
    return x / #ps, y / #ps
end

-- Spawn the roster, frozen (orderIdle: no moving, no targeting, no firing). Any earlier enemies are
-- removed first. Returns the number spawned, or nil and why not.
function ARENA.spawn()
    local list = ARENA.rosterList()
    if #list == 0 then return nil, "The roster is empty: add enemies first (Enemies...)." end
    local cx, cy = ARENA.centre()
    if not cx then return nil, "No player ship in the arena." end
    ARENA.clear()
    local st = ARENA.state
    local heading = RT.valid(RT.player) and RT.player:getHeading() or 0
    local a = math.rad(heading - 90)
    local fx, fy = math.cos(a), math.sin(a)   -- ahead
    local sx, sy = -fy, fx                    -- across
    local n = #list
    for i, name in ipairs(list) do
        local row, col = (i - 1) // ARENA.ROW, (i - 1) % ARENA.ROW
        local in_row = math.min(ARENA.ROW, n - row * ARENA.ROW)
        local across = (col - (in_row - 1) / 2) * ARENA.SPACING_U * U
        local ahead = (st.dist_u + row * ARENA.SPACING_U) * U
        local s = CpuShip():setTemplate(name):setFaction(st.faction)
        s:setPosition(cx + fx * ahead + sx * across, cy + fy * ahead + sy * across)
        s:setHeading((heading + 180) % 360)
        s:orderIdle()
        st.enemies[#st.enemies + 1] = {ship = s, template = name, strength = RT.shipStrength(s).total}
    end
    st.phase, st.spawned_at, st.started_at, st.ended_at, st.result = "frozen", _now(), nil, nil, nil
    st.spawn_dist_u = st.dist_u
    st.spawn_faction = st.faction
    st.roster_text = ARENA.rosterText()
    log("[ARENA] spawned " .. n .. " (" .. st.roster_text .. ") at " .. st.dist_u .. "U, " .. st.faction)
    return n
end

local function _liveEnemies()
    local out = {}
    for _, e in ipairs(ARENA.state.enemies) do if RT.valid(e.ship) then out[#out + 1] = e end end
    return out
end

-- Release the frozen enemies: they hunt the nearest player ship (orderRoaming). Returns false (and
-- why) when there is nothing frozen to start.
function ARENA.start()
    local st = ARENA.state
    if st.phase ~= "frozen" then
        return false, (st.phase == "fighting") and "Already fighting." or "Spawn enemies first."
    end
    local live = _liveEnemies()
    if #live == 0 then return false, "Every enemy is already gone." end
    for _, e in ipairs(live) do e.ship:orderRoaming() end
    -- What the crews had when it started: the report says what the fight cost them.
    st.crews = {}
    for _, p in ipairs(_players()) do
        st.crews[#st.crews + 1] = {ship = p, name = p:getCallSign(), hull = p:getHull(), hull_max = p:getHullMax(),
                                   strength = RT.shipStrength(p).total}
    end
    if not st.started_at then st.started_at = _now(); st.fights = st.fights + 1 end
    st.phase = "fighting"
    log("[ARENA] combat started")
    return true
end

-- Freeze the enemies again (orderIdle) mid-fight; START carries on from there (the clock keeps running).
function ARENA.freeze()
    local st = ARENA.state
    if st.phase ~= "fighting" then return false, "Not fighting." end
    for _, e in ipairs(_liveEnemies()) do e.ship:orderIdle() end
    st.phase = "frozen"
    return true
end

-- Remove every enemy the arena spawned.
function ARENA.clear()
    local st = ARENA.state
    for _, e in ipairs(st.enemies) do
        if RT.valid(e.ship) then e.ship:destroy() end
    end
    st.enemies, st.phase = {}, "empty"
end

local function _mmss(t)
    t = math.max(0, math.floor(t or 0))
    return string.format("%d:%02d", t // 60, t % 60)
end

-- Per frame: the fight is over when every enemy or every player ship is gone.
function ARENA.tick(now)
    local st = ARENA.state
    if st.phase ~= "fighting" then return end
    local result
    if #_liveEnemies() == 0 then result = "won"
    elseif #_players() == 0 then result = "lost" end
    if not result then return end
    st.phase, st.result, st.ended_at = "over", result, now or _now()
    local text = ARENA.report()
    log("[ARENA] " .. text:gsub("\n", " | "))
    pcall(addGMMessage, text)
end

-- ── Restoring the crews ──────────────────────────────────────────────────────
-- A healthy start: full hull, shields, energy, scan probes and missiles (to what the racks hold);
-- every system repaired, cool, unhacked, at 100% power and no coolant (Engineering's defaults).
-- Upgrades and repair crew are untouched. Returns true when the ship was restored.
function ARENA.restore(p)
    if not RT.valid(p) then return false end
    p:setHull(p:getHullMax())
    pcall(function()   -- every segment to its max (the ECS calls: getShieldsMax is a compat shim)
        local levels = {}
        for i = 0, (p:getShieldCount() or 0) - 1 do levels[#levels + 1] = p:getShieldMax(i) end
        if #levels > 0 then p:setShields(table.unpack(levels)) end
    end)
    p:setEnergy(p:getMaxEnergy())
    for _, sys in ipairs(ARENA.SYSTEMS) do
        pcall(function()
            if p:hasSystem(sys) then
                p:setSystemHealthMax(sys, 1)
                p:setSystemHealth(sys, 1)
                p:setSystemHeat(sys, 0)
                p:setSystemHackedLevel(sys, 0)
                p:setSystemPower(sys, 1)
                p:setSystemCoolant(sys, 0)
            end
        end)
    end
    for _, w in ipairs(ARENA.MISSILES) do
        pcall(function() p:setWeaponStorage(w, p:getWeaponStorageMax(w)) end)
    end
    pcall(function() p:setScanProbeCount(p:getMaxScanProbeCount()) end)
    return true
end

function ARENA.restoreAll()
    local n = 0
    for _, p in ipairs(_players()) do if ARENA.restore(p) then n = n + 1 end end
    return n
end

-- Put the player ships back in a line at the arena's centre (0, 0), 1.5U apart, facing north, stopped.
function ARENA.resetPositions()
    local ps = _players()
    for i, p in ipairs(ps) do
        p:setPosition((i - 1 - (#ps - 1) / 2) * 1500, 0)
        p:setHeading(0)
        pcall(function() p:commandImpulse(0) end)
        pcall(function() p:commandWarp(0) end)
    end
    return #ps
end

-- ── Reading it ───────────────────────────────────────────────────────────────
-- One ship type at a glance, for the picker: spawned out of the way, measured, removed.
function ARENA.templateInfo(name)
    local ok, text = pcall(function()
        local s = CpuShip():setTemplate(name):setFaction("Independent"):setPosition(-900000, -900000)
        s:orderIdle()
        local str = RT.shipStrength(s)
        local shields = {}
        for i = 0, (s:getShieldCount() or 0) - 1 do shields[#shields + 1] = math.floor(s:getShieldMax(i)) end
        local beams, dps, reach = 0, 0, 0
        for i = 0, 15 do
            local r = s:getBeamWeaponRange(i)
            if r and r > 0 then
                beams = beams + 1
                local cyc = s:getBeamWeaponCycleTime(i)
                if cyc and cyc > 0 then dps = dps + s:getBeamWeaponDamage(i) / cyc end
                reach = math.max(reach, r)
            end
        end
        local fwd = s:getImpulseMaxSpeed()
        local lines = {
            name,
            string.format("Hull %d, shields %s", math.floor(s:getHullMax()), #shields > 0 and table.concat(shields, "/") or "none"),
            string.format("Impulse %.0f, turn %.0f deg/s", fwd or 0, s:getRotationMaxSpeed() or 0),
            string.format("Beams %d (%.1f damage a second, reach %.1fU), tubes %d", beams, dps, reach / U, s:getWeaponTubeCount() or 0),
            string.format("Strength %d (defense %d, offense %.1f)", str.total, str.defense, str.offense),
        }
        if RT.valid(RT.player) then
            lines[#lines + 1] = string.format("%s now: strength %d", RT.player:getCallSign(), RT.shipStrength(RT.player).total)
        end
        s:destroy()
        return table.concat(lines, "\n")
    end)
    return ok and text or (name .. ": " .. tostring(text))
end

local function _pct(a, b) return (b and b > 0) and math.floor(a / b * 100 + 0.5) or 0 end

-- What the GM sees: the roster and its strength against the crews', the phase and time, and every
-- ship's condition. RT.shipStrength: defense (hull + shields) + 30 x offense (damage a second).
function ARENA.report()
    local st = ARENA.state
    local L = {"=== COMBAT ARENA ==="}
    if #st.enemies == 0 then
        L[#L + 1] = string.format("Roster: %s\nFaction %s, spawn at %dU. Nothing spawned.", ARENA.rosterText(), st.faction, st.dist_u)
    else
        local e_str = 0
        for _, e in ipairs(st.enemies) do e_str = e_str + (e.strength or 0) end
        local p_str = 0
        for _, p in ipairs(_players()) do p_str = p_str + RT.shipStrength(p).total end
        L[#L + 1] = string.format("Enemies: %s (%s, spawned at %dU)", st.roster_text or "?", st.spawn_faction or "?", st.spawn_dist_u or 0)
        L[#L + 1] = string.format("Strength: enemies %d vs crews %d (now)", e_str, p_str)
        local t
        if st.phase == "frozen" and not st.started_at then t = "frozen, not started"
        elseif st.phase == "frozen" then t = "frozen at " .. _mmss(_now() - st.started_at)
        elseif st.phase == "fighting" then t = "fighting, " .. _mmss(_now() - st.started_at)
        elseif st.phase == "over" then
            t = string.format("OVER in %s: the crews %s", _mmss(st.ended_at - st.started_at), st.result == "won" and "won" or "lost")
        else t = st.phase end
        L[#L + 1] = "Phase: " .. t
        local live = _liveEnemies()
        L[#L + 1] = string.format("\nEnemies left: %d of %d", #live, #st.enemies)
        for _, e in ipairs(live) do
            local s = e.ship
            local sh = {}
            for i = 0, (s:getShieldCount() or 0) - 1 do sh[#sh + 1] = math.floor(s:getShieldLevel(i)) end
            L[#L + 1] = string.format("  %s (%s): hull %d%%, shields %s", s:getCallSign(), e.template,
                _pct(s:getHull(), s:getHullMax()), #sh > 0 and table.concat(sh, "/") or "-")
        end
    end
    L[#L + 1] = "\nCrews:"
    local seen = {}
    for _, c in ipairs(st.crews or {}) do
        seen[c.ship] = true
        if RT.valid(c.ship) then
            local p = c.ship
            local sh = {}
            for i = 0, (p:getShieldCount() or 0) - 1 do sh[#sh + 1] = math.floor(p:getShieldLevel(i)) end
            L[#L + 1] = string.format("  %s: hull %d%% (lost %d of %d), shields %s, energy %d", c.name,
                _pct(p:getHull(), p:getHullMax()), math.max(0, math.floor(c.hull - p:getHull())), math.floor(c.hull_max),
                #sh > 0 and table.concat(sh, "/") or "-", math.floor(p:getEnergy()))
        else
            L[#L + 1] = string.format("  %s: DESTROYED", c.name)
        end
    end
    for _, p in ipairs(_players()) do
        if not seen[p] then
            L[#L + 1] = string.format("  %s: hull %d%%, strength %d", p:getCallSign(), _pct(p:getHull(), p:getHullMax()),
                RT.shipStrength(p).total)
        end
    end
    return table.concat(L, "\n")
end

-- ── The GM screen (the arena scenario shows it: ARENA.showGM) ────────────────────────────────────────────────────────────
local showArena, showPicker, showType
ARENA.PAGE = 10   -- ship types per page in the enemy picker

local function say(text) addGMMessage(text) end

showType = function(name, page)
    clearGMFunctions()
    addGMFunction("← Enemies", function() showPicker(page) end)
    addGMFunction(string.format("%s: %d (info)", name, ARENA.count(name)), function() say(ARENA.templateInfo(name)) end)
    for _, step in ipairs({1, 5, -1, -5}) do
        addGMFunction(string.format("%s%d", step > 0 and "+" or "", step), function()
            ARENA.add(name, step)
            showType(name, page)
        end)
    end
    addGMFunction("None", function() ARENA.add(name, -ARENA.MAX_PER_TYPE); showType(name, page) end)
end

showPicker = function(page)
    page = page or 1
    clearGMFunctions()
    addGMFunction("← Arena", showArena)
    addGMFunction(string.format("Roster: %d (show)", ARENA.rosterSize()), function() say("Roster: " .. ARENA.rosterText()) end)
    addGMFunction("Clear roster", function() ARENA.clearRoster(); showPicker(page) end)
    local list = ARENA.templates()
    local pages = math.max(1, math.ceil(#list / ARENA.PAGE))
    page = math.min(page, pages)
    for i = (page - 1) * ARENA.PAGE + 1, math.min(#list, page * ARENA.PAGE) do
        local name = list[i]
        addGMFunction(string.format("%s: %d", name, ARENA.count(name)), function() showType(name, page) end)
    end
    if page > 1 then addGMFunction("< Previous page", function() showPicker(page - 1) end) end
    if page < pages then addGMFunction(string.format("Next page > (%d/%d)", page, pages), function() showPicker(page + 1) end) end
end

showArena = function()
    clearGMFunctions()
    local st = ARENA.state
    addGMFunction(string.format("Enemies... (%d)", ARENA.rosterSize()), function() showPicker(1) end)
    addGMFunction(string.format("Distance - (%dU)", st.dist_u), function() ARENA.nudgeDistance(-1); showArena() end)
    addGMFunction(string.format("Distance + (%dU)", st.dist_u), function() ARENA.nudgeDistance(1); showArena() end)
    addGMFunction("Faction: " .. st.faction, function() ARENA.cycleFaction(); showArena() end)
    addGMFunction("Spawn enemies (frozen)", function()
        local n, why = ARENA.spawn()
        say(n and ARENA.report() or why)
        showArena()
    end)
    addGMFunction("START COMBAT", function()
        local ok, why = ARENA.start()
        if not ok then say(why) end
        showArena()
    end)
    addGMFunction("Freeze enemies", function()
        local ok, why = ARENA.freeze()
        if not ok then say(why) end
        showArena()
    end)
    addGMFunction("Clear enemies", function() ARENA.clear(); showArena() end)
    addGMFunction("Restore player ships", function()
        say(string.format("Restored %d ship(s): hull, shields, energy, systems, missiles, probes.", ARENA.restoreAll()))
    end)
    addGMFunction("Reset positions", function() ARENA.resetPositions() end)
    addGMFunction("Report", function() say(ARENA.report()) end)
    GMCONSOLE.addUpgradesButton(showArena)   -- Ship Upgrades...: grant or revoke any upgrade, per ship
end

function ARENA.showGM() showArena() end
