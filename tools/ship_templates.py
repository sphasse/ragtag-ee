"""The ship templates the game uses, for the Science database's Ships section.

    python3 tools/ship_templates.py --ee <EmptyEpsilon dir>   # refresh tools/ee_ship_templates.txt (after an EE update)
    python3 tools/ship_templates.py                           # print the ships the game uses, and where

EmptyEpsilon's Ships section lists every stock template (155 of them); the Drift uses a few dozen. The game
keeps only the ones it uses (SCIDB.SHIPS_USED, sciencedb.lua). That list is GENERATED: every string literal
in the game's Lua (ee/ragtag/, scenarios/; not attic/ or folders starting with "_", which are parked) that
names a ship template counts as a use, wherever it is (a garrison table, a job archetype, a setTemplate).
tools/check.py regenerates ee/ragtag/ships_used.lua from this (--fix) and fails when it is stale, so a ship
added anywhere in the game comes back into the database by itself.

The stock template names come from tools/ee_ship_templates.txt ("<template>\t<name shown>"), made by running
EE's own scripts/shipTemplates.lua under a stub (tools/list_ship_templates.lua), so check.py needs no EE.
"""
from __future__ import annotations

import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LIST = ROOT / "tools" / "ee_ship_templates.txt"
OUT = ROOT / "ee" / "ragtag" / "ships_used.lua"
# A literal that happens to be a template's name but means something else: (name, file under ee/ or repo root).
NOT_SHIPS = {
    ("Sentinel", "ragtag/jobs/_engine.lua"),     # the short name of Sentinel Fleet Yard on the job board
}
LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"|\'((?:[^\'\\\n]|\\.)*)\'')


def stock() -> dict[str, str]:
    """Stock template name -> the name the Science database shows."""
    out = {}
    for line in LIST.read_text(encoding="utf-8").splitlines():
        if "\t" in line:
            name, shown = line.split("\t", 1)
            out[name] = shown
    return out


def lua_files() -> list[Path]:
    files = []
    for base in (ROOT / "ee" / "ragtag", ROOT / "scenarios"):
        for f in sorted(base.rglob("*.lua")):
            rel = f.relative_to(base).parts
            if "attic" in rel or any(p.startswith("_") for p in rel[:-1]) or f == OUT:
                continue
            files.append(f)
    return files


def used() -> dict[str, list[str]]:
    """Template name -> the files that name it."""
    names = stock()
    found: dict[str, set[str]] = {}
    for f in lua_files():
        text = f.read_text(encoding="utf-8")
        for m in LITERAL.finditer(text):
            s = m.group(1) if m.group(1) is not None else m.group(2)
            rel = str(f.relative_to(ROOT / "ee")) if "ee/ragtag" in str(f) else str(f.relative_to(ROOT))
            if s in names and (s, rel) not in NOT_SHIPS:
                found.setdefault(s, set()).add(rel)
    return {k: sorted(v) for k, v in sorted(found.items())}


def render() -> str:
    names = stock()
    lines = ["-- Generated by tools/check.py --fix (tools/ship_templates.py). Do not edit.",
             "-- The ship templates the game's Lua names: the Science database's Ships section keeps these and",
             "-- drops the rest of EmptyEpsilon's stock ships. Name a template anywhere in the game and it is listed.",
             "SCIDB = SCIDB or {}",
             "SCIDB.SHIPS_USED = {"]
    for name, files in used().items():
        where = ", ".join(f.replace("ragtag/", "", 1) for f in files[:3]) + (", ..." if len(files) > 3 else "")
        shown = names[name]
        lines.append(f'    ["{name}"] = "{shown}",   -- {where}')
    lines.append("}")
    return "\n".join(lines) + "\n"


def refresh(ee: Path) -> None:
    scripts = next((p for p in (ee / "scripts", ee / "EmptyEpsilon" / "scripts",
                                ee / "_build" / "EmptyEpsilon.app" / "Contents" / "Resources" / "scripts")
                    if (p / "shipTemplates.lua").exists()), None)
    if not scripts:
        raise SystemExit(f"No scripts/shipTemplates.lua under {ee}")
    r = subprocess.run(["lua5.4", str(ROOT / "tools" / "list_ship_templates.lua"), str(scripts)],
                       capture_output=True, text=True, check=True)
    LIST.write_text(r.stdout, encoding="utf-8")
    print(f"wrote {LIST.relative_to(ROOT)} ({len(r.stdout.splitlines())} templates from {scripts})")


if __name__ == "__main__":
    if "--ee" in sys.argv:
        refresh(Path(sys.argv[sys.argv.index("--ee") + 1]))
    else:
        for name, files in used().items():
            print(f"{name}: {', '.join(files)}")
