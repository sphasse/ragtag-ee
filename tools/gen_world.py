"""Generate director/generated/world.md: the universe as the AI director sees it.

    python tools/gen_world.py

Built from the universe data, so universe contributors never have to edit
campaign bibles. tools/check.py fails if this file is out of date.
"""
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import verse_data  # noqa: E402

DANGER = {0: "safe", 1: "risky", 2: "dangerous", 3: "DEADLY"}
FACTIONS = [
    ("Independent", "the crew, independent stations and freighters. Friendly but mercenary."),
    ("Concord", "the law. Customs patrols, permits, inspections. Concord stations refuse service to ships flagged wanted."),
    ("Corsairs", "pirate crews of the risky and dangerous zones. Greedy and theatrical."),
    ("Hollow", "raiders from beyond the Pale Sun. They never talk. Keep stories about them frightening, never explicit. Never spawn or summon them."),
    ("Relic", "automated war drones that still guard old battlefields."),
    ("Unknown", "silent ships with no transponder that spacers call 'the Ghosts'. Only tones. Not hostile."),
]


def render(d: dict) -> str:
    regions = d["regions"]

    def region_of(x, y):
        best, best_r = None, 1e9
        for r in regions:
            if (x - r["x"]) ** 2 + (y - r["y"]) ** 2 <= r["r"] ** 2 and r["r"] < best_r:
                best, best_r = r, r["r"]
        return best["name"] if best else "open space"

    by_region = defaultdict(list)
    for s in d["stations"]:
        by_region[region_of(s["x"], s["y"])].append(s)
    lines = ["<!-- Generated by tools/gen_world.py from ee/ragtag/verse/. Do not edit by hand. -->"]
    if d.get("lore"):
        lines.append("### Background")
        lines += list(d["lore"])
        lines.append("")
    lines.append("### Regions (danger: safe / risky / dangerous / DEADLY)")
    for r in sorted(regions, key=lambda r: (r["danger"], r["name"])):
        st = by_region.get(r["name"], [])
        names = ", ".join(f'{s["cs"]}{" (shipwright)" if s.get("shop") else ""}' for s in st)
        lines.append(f'- {r["name"][0].upper() + r["name"][1:]} [{DANGER[r["danger"]]}]: {r["desc"]}' + (f" Stations: {names}." if names else ""))
    if by_region.get("open space"):
        lines.append("- Elsewhere: " + ", ".join(s["cs"] for s in by_region["open space"]) + ".")
    lines.append("")
    lines.append("### Factions (EmptyEpsilon faction names)")
    for name, desc in FACTIONS:
        lines.append(f"- {name}: {desc}")
    lines.append("")
    route_text = "; ".join(f'{r["id"]} ({r["fac"]}): {", ".join(r["stations"])}' for r in d["routes"])
    lines.append(f"### Traffic\nFreighters run these routes and can be hailed: {route_text}. "
                 "The richest salvage lies in the most dangerous places.")
    return "\n".join(lines) + "\n"


OUT = verse_data.ROOT / "director" / "generated" / "world.md"

if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render(verse_data.load()))
    print("wrote", OUT.relative_to(verse_data.ROOT))
